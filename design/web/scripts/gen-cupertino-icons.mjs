// Regenerates src/components/Icon/cupertinoIcons.ts from the app's
// lib/src/theme/app_icons.dart and the Flutter SDK's CupertinoIcons codepoints.
// Usage: node scripts/gen-cupertino-icons.mjs [path/to/flutter/packages/flutter/lib/src/cupertino/icons.dart]
import { execFileSync } from "node:child_process";
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const web = join(import.meta.dirname, "..");
const repo = join(web, "..", "..");

function sdkIconsPath() {
  if (process.argv[2]) return process.argv[2];
  const flutter = realpathSync(
    execFileSync("which", ["flutter"], { encoding: "utf8" }).trim(),
  );
  return join(
    dirname(dirname(flutter)),
    "packages/flutter/lib/src/cupertino/icons.dart",
  );
}

const sdk = readFileSync(sdkIconsPath(), "utf8");
const codepoints = new Map();
for (const m of sdk.matchAll(
  /static const IconData (\w+) = IconData\(\s*(0x[0-9a-f]+)/g,
)) {
  codepoints.set(m[1], Number.parseInt(m[2], 16));
}

const app = readFileSync(join(repo, "lib/src/theme/app_icons.dart"), "utf8");
const sets = [...app.matchAll(/static const (\w+) = AppIconSet\(([^;]*)\);/g)];
const materialToApple = new Map();
// Every set's glyph, also one whose Material name an earlier set took
// (pinOutline's pin), so `Icon apple="pin"` can draw it.
const pairedGlyphs = new Set();
const skipped = [];
for (const [, field, args] of sets) {
  const m = args.match(/^\s*Icons\.(\w+),\s*CupertinoIcons\.(\w+),?\s*$/);
  if (!m) {
    skipped.push(`${field}(${args.replace(/\s+/g, " ").trim()})`);
    continue;
  }
  pairedGlyphs.add(m[2]);
  // The first set wins when two share a Material glyph (sidebar, inspector).
  if (!materialToApple.has(m[1])) materialToApple.set(m[1], m[2]);
}

// Glyphs Apple screens use that AppIcons doesn't pair with a Material icon:
// the navigation bar's back chevron and the pull-down menu's checkmark.
const extras = ["back", "checkmark"];

const appleNames = new Set([...pairedGlyphs, ...extras]);
const missing = [...appleNames].filter((n) => !codepoints.has(n));
if (missing.length) throw new Error(`no codepoint for ${missing.join(", ")}`);

const lines = (entries) =>
  entries
    .sort()
    .map(([key, value]) => `  ${key}: ${value},`)
    .join("\n");
const glyphs = lines(
  [...appleNames].map((n) => [n, `0x${codepoints.get(n).toString(16)}`]),
);
const pairs = lines([...materialToApple].map(([m, a]) => [m, `"${a}"`]));

writeFileSync(
  join(web, "src/components/Icon/cupertinoIcons.ts"),
  `// Generated by scripts/gen-cupertino-icons.mjs from lib/src/theme/app_icons.dart. Do not edit.

/** CupertinoIcons glyph codepoints, by Flutter's \`CupertinoIcons.*\` name. */
export const cupertinoGlyphs = {
${glyphs}
} as const;

export type CupertinoIconName = keyof typeof cupertinoGlyphs;

/** The Apple glyph the app shows for each Flutter \`Icons.*\` name (AppIcons). */
export const materialToCupertino: Record<string, CupertinoIconName> = {
${pairs}
};
`,
);
console.log(
  `${sets.length} AppIcons sets: ${materialToApple.size} Material names paired, ${appleNames.size} Apple glyphs`,
);
for (const s of skipped) console.log(`  not a Material/Cupertino pair: ${s}`);
